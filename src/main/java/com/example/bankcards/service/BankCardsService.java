package com.example.bankcards.service;

import com.example.bankcards.dto.BankCardDto;
import com.example.bankcards.dto.CreateBankCardDto;
import com.example.bankcards.entity.CardStatus;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;

import java.math.BigDecimal;
import java.time.YearMonth;

/**
 * Интерфейс {@code BankCardsService} определяет контракт для операций, связанных с управлением банковскими картами.
 * <p>
 * Он предоставляет методы для создания, просмотра, блокировки, активации, удаления и поиска банковских карт.
 * Этот сервис предназначен для выполнения бизнес-логики, связанной с жизненным циклом банковских карт в системе.
 * </p>
 */
public interface BankCardsService {
    /**
     * Создает новую банковскую карту на основе предоставленных данных.
     * <p>
     * Этот метод обрабатывает логику создания карты, включая, возможно, генерацию номера карты, CVV,
     * установку начального статуса и сохранение в базе данных.
     * </p>
     *
     * @param createDto Объект {@link CreateBankCardDto}, содержащий все необходимые данные для создания новой карты.
     */
    void create(CreateBankCardDto createDto);

    /**
     * Возвращает страницу всех существующих банковских карт.
     * <p>
     * Метод поддерживает пагинацию и сортировку результатов.
     * </p>
     *
     * @param pageable Объект {@link Pageable}, определяющий параметры пагинации (номер страницы, размер страницы) и сортировки.
     * @return Объект {@link Page}, содержащий список {@link BankCardDto} и информацию о пагинации.
     */
    Page<BankCardDto> getAllCards(Pageable pageable);

    /**
     * Блокирует банковскую карту по её идентификатору.
     * <p>
     * Изменяет статус карты на "заблокирована". Это действие обычно необратимо или требует отдельной активации.
     * </p>
     *
     * @param cardId Уникальный идентификатор банковской карты, которую необходимо заблокировать.
     */
    void blockCard(Long cardId);

    /**
     * Активирует ранее заблокированную или неактивную банковскую карту по её идентификатору.
     * <p>
     * Изменяет статус карты на "активна".
     * </p>
     *
     * @param cardId Уникальный идентификатор банковской карты, которую необходимо активировать.
     */
    void activateCard(Long cardId);

    /**
     * Удаляет банковскую карту по её идентификатору.
     * <p>
     * Это действие, как правило, приводит к безвозвратному удалению карты из системы.
     * </p>
     *
     * @param cardId Уникальный идентификатор банковской карты, которую необходимо удалить.
     */
    void delete(Long cardId);

    /**
     * Инициирует запрос на блокировку банковской карты по её идентификатору.
     * <p>
     * Этот метод может использоваться для пользовательских запросов на блокировку,
     * которые могут требовать дополнительного подтверждения или менять статус карты
     * на "ожидает блокировки" (pending block), в отличие от немедленной административной блокировки.
     * </p>
     *
     * @param cardId Уникальный идентификатор банковской карты, для которой запрашивается блокировка.
     */
    void requestBlock(Long cardId);

/**
 * Осуществляет поиск банковских карт текущего пользователя с применением различных фильтров.
 * <p>
 * Поиск может быть выполнен по статусу карты, минимальному балансу и/или дате истечения срока действия,
 * начиная с указанного месяца и года. Результаты возвращаются в виде страницы с поддержкой пагинации.
 * </p>
 *
 * @param status         (Опционально) {@link CardStatus} для фильтрации карт по их текущему статусу.
 *                       Если {@code null}, этот фильтр не применяется.
 * @param minBalance     (Опционально) {@link BigDecimal} для фильтрации карт, баланс которых равен или
 *                       больше указанного значения. Если {@code null}, этот фильтр не применяется.
 * @param expiryDateFrom (Опционально) {@link YearMonth} для фильтрации карт, срок действия которых
 *                       истекает начиная с указанного месяца и года (включительно). Если {@code null},
 *                       этот фильтр не применяется.
 * @param pageable       Объект {@link Pageable}, определяющий параметры пагинации и сортировки результатов.
 * @return Объект {@link Page}, содержащий список {@link BankCardDto}, соответствующих критериям поиска,
 *         и информацию о пагинации.
 */
    Page<BankCardDto> searchCurrentUserCards(CardStatus status, BigDecimal minBalance, YearMonth expiryDateFrom, Pageable pageable);
}
