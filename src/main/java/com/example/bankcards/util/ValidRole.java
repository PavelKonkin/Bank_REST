package com.example.bankcards.util;

import jakarta.validation.Constraint;
import jakarta.validation.Payload;

import java.lang.annotation.*;

/**
 * <p>Аннотация для проверки, что строковое значение является допустимым именем константы
 * заданного перечисления ({@code enum}).</p>
 *
 * <p>Эта аннотация используется для валидации строковых полей, которые должны соответствовать
 * именам констант определенного перечисления, например, для валидации ролей пользователей.</p>
 *
 * <p>Валидация выполняется классом {@link EnumNameValidator}, который проверяет,
 * существует ли предоставленное строковое значение в указанном {@code enumClass}.</p>
 *
 * <p>Может быть применена к методам, полям, другим аннотациям и параметрам.</p>
 *
 * @see EnumNameValidator
 * @see Constraint
 */
@Documented
@Constraint(validatedBy = EnumNameValidator.class)
@Target({ElementType.METHOD, ElementType.FIELD, ElementType.ANNOTATION_TYPE, ElementType.PARAMETER})
@Retention(RetentionPolicy.RUNTIME)
public @interface ValidRole {
    /**
     * <p>Возвращает сообщение об ошибке, которое будет использоваться, если проверка не удалась.</p>
     *
     * <p>По умолчанию: "Недопустимое значение роли. Допустимые значения: {allowedValues}".</p>
     * <p>Плейсхолдер {@code {allowedValues}} будет заменен списком допустимых значений из перечисления,
     * указанного в {@link #enumClass()}.</p>
     *
     * @return Сообщение об ошибке.
     */
    String message() default "Недопустимое значение роли. Допустимые значения: {allowedValues}";

    /**
     * <p>Позволяет указать группы валидации, к которым принадлежит эта проверка.</p>
     *
     * <p>Используется для выборочной валидации частей объекта или различных сценариев.</p>
     *
     * @return Массив классов, представляющих группы валидации. По умолчанию пустой массив.
     */
    Class<?>[] groups() default {};

    /**
     * <p>Позволяет прикрепить метаданные или полезную нагрузку к ограничению.</p>
     *
     * <p>Может использоваться для передачи информации о степени серьезности нарушения
     * или другой контекстной информации.</p>
     *
     * @return Массив классов, расширяющих {@link Payload}. По умолчанию пустой массив.
     */
    Class<? extends Payload>[] payload() default {};

    /**
     * <p>Обязательный параметр, указывающий класс перечисления ({@code enum}),
     * против которого будет выполняться проверка.</p>
     *
     * <p>Валидатор {@link EnumNameValidator} использует этот класс для получения
     * всех допустимых имен констант перечисления.</p>
     *
     * <p>Например, если вы хотите проверить, что строка является допустимой {@code UserRole},
     * вы должны указать {@code enumClass = UserRole.class}.</p>
     *
     * @return Класс перечисления, который содержит допустимые значения.
     */
    Class<? extends Enum<?>> enumClass();
}
